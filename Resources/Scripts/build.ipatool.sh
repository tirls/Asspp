#!/bin/bash
#
# Builds the ipatool bridge for iOS devices:
#   Vendor/IPATool/iphoneos/lib/libipatoolbridge.a   (Go c-archive: ipatool + Asspp overlay)
#   Vendor/IPATool/iphoneos/lib/libunicorn.a         (Unicorn TCI interpreter, AArch64 guest)
#   Vendor/IPATool/iphoneos/include/                 (C header + Swift module map)
#   Configuration/IPATool.generated.xcconfig         (included optionally by Base.xcconfig)
#
# Without these outputs the app still builds and keeps the ApplePackage store path.
#
# Requirements: macOS with Xcode, Go (GOTOOLCHAIN=auto fetches ipatool's version), CMake.
# Usage: Resources/Scripts/build.ipatool.sh [srcroot]

set -euo pipefail

SRCROOT=$(cd "${1:-$(dirname "$0")/../..}" && pwd)

# ipatool main after v2.8.0: Store AMD proofs, kbsync ent/download, native login.
IPATOOL_REPOSITORY="https://github.com/majd/ipatool.git"
IPATOOL_REVISION="e0e2908dc866651cbd6ad86edd954119c003c46b"

# Unicorn 2.1.1 with the TCI interpreter (no JIT, no executable memory), as
# used by Asspp's earlier SAP work. Upstream Unicorn cannot run without JIT on iOS.
UNICORN_REVISION="53471ef9cf480fab094bf13db3e5d2f9e2c30dc5"
UNICORN_ARCHIVE_SHA256="e395e308aae3629aebe14d6692ce989018e52060c3e0506d02d01f2047f52a47"

DEPLOYMENT_TARGET="${IPHONEOS_DEPLOYMENT_TARGET:-17.0}"
WORK="${ASSPP_IPATOOL_WORK:-$SRCROOT/build/IPATool}"
OUTPUT="$SRCROOT/Vendor/IPATool/iphoneos"
XCCONFIG="$SRCROOT/Configuration/IPATool.generated.xcconfig"

for tool in git go cmake xcrun shasum; do
    command -v "$tool" >/dev/null 2>&1 || {
        echo "[-] $tool is required" >&2
        exit 1
    }
done

SDKROOT=$(xcrun --sdk iphoneos --show-sdk-path)
CLANG=$(xcrun --sdk iphoneos --find clang)
TARGET_FLAGS="-arch arm64 -isysroot $SDKROOT -miphoneos-version-min=$DEPLOYMENT_TARGET"

mkdir -p "$WORK"

echo "[*] preparing ipatool $IPATOOL_REVISION"
IPATOOL_SOURCE="$WORK/ipatool"
if [ ! -d "$IPATOOL_SOURCE/.git" ]; then
    git init -q "$IPATOOL_SOURCE"
    git -C "$IPATOOL_SOURCE" remote add origin "$IPATOOL_REPOSITORY"
fi
if [ "$(git -C "$IPATOOL_SOURCE" rev-parse -q --verify HEAD 2>/dev/null || true)" != "$IPATOOL_REVISION" ]; then
    git -C "$IPATOOL_SOURCE" fetch -q --depth 1 origin "$IPATOOL_REVISION"
fi
git -C "$IPATOOL_SOURCE" checkout -q --force "$IPATOOL_REVISION"
git -C "$IPATOOL_SOURCE" clean -q -fdx
cp -R "$SRCROOT/IPAToolBridge/overlay/." "$IPATOOL_SOURCE/"

echo "[*] preparing Unicorn TCI $UNICORN_REVISION"
UNICORN_ARCHIVE="$WORK/unicorn-$UNICORN_REVISION.tar.gz"
UNICORN_SOURCE="$WORK/unicorn-$UNICORN_REVISION"
if [ ! -f "$UNICORN_ARCHIVE" ] || ! echo "$UNICORN_ARCHIVE_SHA256  $UNICORN_ARCHIVE" | shasum -a 256 -c - >/dev/null 2>&1; then
    curl -fL --retry 3 "https://codeload.github.com/Naville/unicorn/tar.gz/$UNICORN_REVISION" -o "$UNICORN_ARCHIVE.pending"
    echo "$UNICORN_ARCHIVE_SHA256  $UNICORN_ARCHIVE.pending" | shasum -a 256 -c -
    mv "$UNICORN_ARCHIVE.pending" "$UNICORN_ARCHIVE"
    rm -rf "$UNICORN_SOURCE"
fi
if [ ! -d "$UNICORN_SOURCE" ]; then
    tar -xzf "$UNICORN_ARCHIVE" -C "$WORK"
fi

UNICORN_BUILD="$WORK/unicorn-build-iphoneos"
if [ ! -f "$UNICORN_BUILD/libunicorn.a" ]; then
    rm -rf "$UNICORN_BUILD"
    cmake -S "$UNICORN_SOURCE" -B "$UNICORN_BUILD" \
        -DCMAKE_SYSTEM_NAME=iOS \
        -DCMAKE_OSX_SYSROOT="$SDKROOT" \
        -DCMAKE_OSX_ARCHITECTURES=arm64 \
        -DCMAKE_OSX_DEPLOYMENT_TARGET="$DEPLOYMENT_TARGET" \
        -DCMAKE_C_COMPILER="$CLANG" \
        -DCMAKE_BUILD_TYPE=Release \
        -DBUILD_SHARED_LIBS=OFF \
        -DUNICORN_INTERPRETER=ON \
        -DUNICORN_ARCH=aarch64 \
        -DUNICORN_BUILD_TESTS=OFF \
        -DUNICORN_INSTALL=OFF
    cmake --build "$UNICORN_BUILD" --parallel "$(sysctl -n hw.ncpu)"
fi

echo "[*] building Go c-archive"
BRIDGE_BUILD="$WORK/bridge-iphoneos"
rm -rf "$BRIDGE_BUILD"
mkdir -p "$BRIDGE_BUILD"
(
    cd "$IPATOOL_SOURCE"
    export GOTOOLCHAIN="${GOTOOLCHAIN:-auto}"
    export GOOS=ios GOARCH=arm64 CGO_ENABLED=1
    export CC="$CLANG"
    export CGO_CFLAGS="$TARGET_FLAGS"
    export CGO_LDFLAGS="$TARGET_FLAGS"
    go build -trimpath -buildmode=c-archive -ldflags="-s -w" \
        -o "$BRIDGE_BUILD/libipatoolbridge.a" ./asspp/bridge
)

echo "[*] installing outputs"
rm -rf "$OUTPUT"
mkdir -p "$OUTPUT/lib" "$OUTPUT/include"
cp "$BRIDGE_BUILD/libipatoolbridge.a" "$OUTPUT/lib/"
cp "$UNICORN_BUILD/libunicorn.a" "$OUTPUT/lib/"
cp "$BRIDGE_BUILD/libipatoolbridge.h" "$OUTPUT/include/"
cat >"$OUTPUT/include/module.modulemap" <<'EOF'
module IPAToolBridge {
    header "libipatoolbridge.h"
    export *
}
EOF
cat >"$OUTPUT/REVISIONS" <<EOF
ipatool $IPATOOL_REVISION
unicorn $UNICORN_REVISION
EOF

# purego resolves Unicorn with dlsym(RTLD_DEFAULT), so its symbols must be
# linked even though nothing references them and must stay exported.
cat >"$XCCONFIG" <<'EOF'
// Generated by Resources/Scripts/build.ipatool.sh. Do not edit.
ASSPP_IPATOOL_DIR = $(SRCROOT)/Vendor/IPATool/iphoneos
SWIFT_INCLUDE_PATHS[sdk=iphoneos*] = $(inherited) $(ASSPP_IPATOOL_DIR)/include
LIBRARY_SEARCH_PATHS[sdk=iphoneos*] = $(inherited) $(ASSPP_IPATOOL_DIR)/lib
OTHER_LDFLAGS[sdk=iphoneos*] = $(inherited) -lipatoolbridge -Wl,-force_load,$(ASSPP_IPATOOL_DIR)/lib/libunicorn.a -Wl,-export_dynamic -lresolv -framework Security -framework CoreFoundation
OTHER_SWIFT_FLAGS[sdk=iphoneos*] = $(inherited) -DASSPP_IPATOOL
EOF

echo "[+] ipatool bridge ready: $OUTPUT"
